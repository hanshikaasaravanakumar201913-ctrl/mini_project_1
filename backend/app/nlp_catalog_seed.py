def seed_canonical_nlp_catalog(db: Session) -> None:
    """Idempotently populates canonical medicines and verified multilingual aliases across 13 languages."""
    existing_codes = {
        row[0]: row[1]
        for row in db.query(CanonicalMedicineCatalog.canonical_code, CanonicalMedicineCatalog.id).all()
    }

    for entry in CANONICAL_SEED_DATA:
        canon_id = existing_codes.get(entry["canonical_code"])
        if canon_id is None:
            canon = CanonicalMedicineCatalog(
                canonical_code=entry["canonical_code"],
                canonical_name=entry["canonical_name"],
                generic_name=entry["generic_name"],
                active_ingredient=entry["active_ingredient"],
                brand_names_json=json.dumps(entry["brand_names"]),
                strength=entry["strength"],
                dosage_form=entry["dosage_form"],
                therapeutic_category=entry["therapeutic_category"],
                simple_explanation=entry["simple_explanation"],
                review_status="APPROVED",
            )
            db.add(canon)
            db.flush()
            canon_id = canon.id
            existing_codes[entry["canonical_code"]] = canon_id

        existing_aliases = {
            (row[0], row[1])
            for row in db.query(
                MedicineMultilingualAlias.language_code,
                MedicineMultilingualAlias.normalized_alias,
            )
            .filter(MedicineMultilingualAlias.canonical_medicine_id == canon_id)
            .all()
        }

        for lang_code, alias_text, alias_type in entry["aliases"]:
            norm = clean_text_for_matching(alias_text)
            if (lang_code, norm) in existing_aliases:
                continue
            lang_meta = LANGUAGE_BY_CODE.get(lang_code, {})
            db.add(
                MedicineMultilingualAlias(
                    canonical_medicine_id=canon_id,
                    language_code=lang_code,
                    alias_text=alias_text,
                    normalized_alias=norm,
                    alias_type=alias_type,
                    script_name=lang_meta.get("script", "Latin"),
                    review_status="APPROVED",
                    notes="Seeded canonical multilingual alias",
                )
            )
            existing_aliases.add((lang_code, norm))

    db.commit()
